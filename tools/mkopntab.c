/*
 * mkopntab.c - the YM2612's tables for the DSP (src/opnfast.c's: the sine,
 * the gains, the LFO's) as C arrays for the 68030 to load: made on the
 * build machine, with its floating point, so that the Atari's are the
 * model's word for word (EPlay itself has none).
 *
 *	mkopntab OUT.H
 */
#include <stdio.h>
#include "opnfast.h"

static OPNF f;

static void table(FILE *o, const char *name, const long *v, int n)
{
	int i;
	fprintf(o, "static const unsigned long %s[%d] = {", name, n);
	for (i = 0; i < n; i++)
		fprintf(o, "%s0x%06lxUL,", i % 6 ? " " : "\n\t", (unsigned long)v[i] & 0xffffff);
	fprintf(o, "\n};\n");
}

int main(int argc, char **argv)
{
	FILE *o;
	if (argc < 2 || !(o = fopen(argv[1], "w")))
		return 1;
	opnf_init(&f);
	fprintf(o, "/* SPDX-License-Identifier: GPL-2.0-or-later\n * Copyright (C) 2026 AERA | Erez Yaary\n"
		   " * generated by tools/mkopntab.c from src/opnfast.c - do not edit */\n");
	table(o, "opn_sin", f.sin_tab, 1024);
	table(o, "opn_gain", f.gain_tab, OPNF_GAINS);
	table(o, "opn_tri", f.triw, 128);
	table(o, "opn_pmw", f.pmw, 128);
	fclose(o);
	return 0;
}
