/*
 * mkopltab.c - the YM3812's and the YMF262's tables for the DSP (src/
 * oplfast.c's: the sine's first quarter and the 32 factors the eight
 * waveforms are made from, src/oplexp.h, each of their words checked
 * against the model's here; the gains not 0, the tremolo's, the
 * vibrato's) as C arrays for the 68030 to load: made on the build machine, with its floating point, so
 * that the Atari's are the model's word for word (EPlay itself has none).
 *
 *	mkopltab OUT.H
 */
#include <stdio.h>
#include <math.h>
#include "oplexp.h"

static OPLF f;

static void table(FILE *o, const char *name, const long *v, int n)
{
	int i;
	fprintf(o, "static const unsigned long %s[%d] = {", name, n);
	for (i = 0; i < n; i++)
		fprintf(o, "%s0x%06lxUL,", i % 6 ? " " : "\n\t", (unsigned long)v[i] & 0xffffff);
	fprintf(o, "\n};\n");
}

int main(int argc, char **argv)
{
	FILE *o;
	if (argc < 2 || !(o = fopen(argv[1], "w")))
		return 1;
	oplf_init(&f);
	fprintf(o, "/* SPDX-License-Identifier: GPL-2.0-or-later\n * Copyright (C) 2026 AERA | Erez Yaary\n"
		   " * generated by tools/mkopltab.c from src/oplfast.c - do not edit */\n");
	{
		static long sq[256];
		static unsigned long usq[256];
		static unsigned long long rq[32];
		int i, w, bad = 0;
		for (i = 0; i < 256; i++)
			usq[i] = (unsigned long)(sq[i] = f.wave[0][i]);
		for (i = 0; i < 32; i++)
			rq[i] = (unsigned long long)floorl(powl(2.0L, -i / 32.0L) * 1099511627776.0L + 0.5L);
		/* (each word the 68030 makes against the model's) */
		for (w = 0; w < 8; w++)
			for (i = 0; i < 1024; i++)
				if (oplx_wave(usq, rq, w, i) != ((unsigned long)f.wave[w][i] & 0xffffff) && bad++ < 5)
					fprintf(stderr, "mkopltab: waveform %d at %d: %06lx, the model's %06lx\n", w, i,
						oplx_wave(usq, rq, w, i), (unsigned long)f.wave[w][i] & 0xffffff);
		for (i = OPL_GAIN_N; i < OPLF_GAINS; i++)
			if (f.gain_tab[i] && bad++ < 5)
				fprintf(stderr, "mkopltab: gain %d isn't 0\n", i);
		if (bad) {
			fclose(o);
			remove(argv[1]);
			return 1;
		}
		table(o, "opl_sinq", sq, 256);
		fprintf(o, "static const unsigned long long opl_rq[32] = {");
		for (i = 0; i < 32; i++)
			fprintf(o, "%s0x%llxULL,", i % 3 ? " " : "\n\t", rq[i]);
		fprintf(o, "\n};\n");
	}
	table(o, "opl_gain", f.gain_tab, OPL_GAIN_N);
	table(o, "opl_am", &f.am_tab[0][0], 512);
	table(o, "opl_pmw", f.pmw, 8);
	fclose(o);
	return 0;
}
