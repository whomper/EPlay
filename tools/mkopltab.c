/*
 * mkopltab.c - the YM3812's and the YMF262's tables for the DSP (src/
 * oplfast.c's: the first four waveforms, the logarithmic saw the OPL3's
 * last is made from, the gains, the tremolo's, the vibrato's) as C arrays
 * for the 68030 to load (it makes waveforms 4 to 7 from them, as
 * oplf_init does): made on the build machine, with its floating point, so
 * that the Atari's are the model's word for word (EPlay itself has none).
 *
 *	mkopltab OUT.H
 */
#include <stdio.h>
#include "oplfast.h"

static OPLF f;

static void table(FILE *o, const char *name, const long *v, int n)
{
	int i;
	fprintf(o, "static const unsigned long %s[%d] = {", name, n);
	for (i = 0; i < n; i++)
		fprintf(o, "%s0x%06lxUL,", i % 6 ? " " : "\n\t", (unsigned long)v[i] & 0xffffff);
	fprintf(o, "\n};\n");
}

int main(int argc, char **argv)
{
	FILE *o;
	if (argc < 2 || !(o = fopen(argv[1], "w")))
		return 1;
	oplf_init(&f);
	fprintf(o, "/* SPDX-License-Identifier: GPL-2.0-or-later\n * Copyright (C) 2026 AERA | Erez Yaary\n"
		   " * generated by tools/mkopltab.c from src/oplfast.c - do not edit */\n");
	table(o, "opl_wave", &f.wave[0][0], 4096);
	{
		static long ramp[512];
		int i;
		for (i = 0; i < 512; i++)
			ramp[i] = oplf_ramp(i);
		table(o, "opl_ramp", ramp, 512);
	}
	table(o, "opl_gain", f.gain_tab, OPLF_GAINS);
	table(o, "opl_am", &f.am_tab[0][0], 512);
	table(o, "opl_pmw", f.pmw, 8);
	fclose(o);
	return 0;
}
