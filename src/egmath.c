/* 2^x, Q23, for x (Q24) at most 0 */
long eg_exp2(long long x)
{
	unsigned long long y = (unsigned long long)-x;
	long ip = (long)(y >> 24), f = (long)(y & 0xffffff), i = f >> 16, r;
	long a, b;
	if (ip >= 24)
		return 0;
	a = exp2_frac[i];
	b = exp2_frac[i + 1];
	r = a - (long)(((long long)(a - b) * (f & 0xffff)) >> 16);
	return r >> ip;
}
